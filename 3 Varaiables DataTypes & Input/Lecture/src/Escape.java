public class Escape {
    public static void main(String[] args) {
        System.out.println("Hello \"MannKandoi\"...");

        System.out.println("Hello \tMannKandoi");
        System.out.println("Hello \\MannKandoi\\");
        System.out.println("Mann \nKandoi");

        System.out.println("Hello\bMannKandoi");
    }
}
